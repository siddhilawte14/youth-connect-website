export const createSampleAttendees = (count: number, eventPrefix: string): EventAttendee[] => {
  const result: EventAttendee[] = [];
  for (let i = 0; i < count; i++) {
    const student = SAMPLE_STUDENTS[i % SAMPLE_STUDENTS.length];
    const uniqueEmail = i < SAMPLE_STUDENTS.length ? student.email : `${student.email.split('@')[0]}.${i + 1}@${student.email.split('@')[1]}`;
    result.push({
      id: `att-${eventPrefix}-${1000 + i}`,
      name: i < SAMPLE_STUDENTS.length ? student.name : `${student.name} ${String.fromCharCode(65 + (i % 26))}.`,
      email: uniqueEmail,
      timestamp: `2026-08-${String(15 + (i % 7)).padStart(2, '0')} ${String(9 + (i % 8)).padStart(2, '0')}:${String((i * 11) % 60).padStart(2, '0')} AM`,
      college: student.college,
      department: student.department,
      ticketId: `TKT-${8000 + i}-${eventPrefix.substring(0, 3).toUpperCase()}`,
    });
  }
  return result;
};

